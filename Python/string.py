name = "Priyam Pratim" # Python string aree immutable

# String Method : 
# Uppercase Method : Uppercase method do not change the original Method
print(name.upper()) # PRIYAM PRATIM
print(name) # Priyam Pratim

# Lowercase Method
print(name.lower())

# Find Method
print(name.find("ratim")) #It will give the index

# Replace
print(name.replace("Priyam Pratim", "Tony Stark"))
print(name.replace("Pratim", "Baishya"))

# Check for  presence
print('X' in name) # False
print('P' in name) # True


